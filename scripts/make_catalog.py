"""Milestone 4 cross-era catalog -> data/final/catalog/ + docs/CATALOG.md.

  match_1930s_film.mp4, match_1970s_tv.mp4, match_1990s_broadcast.mp4
      the full Larwood-vs-Bradman match in one era, title cards filmed in that era
  match_crossera.mp4
      Larwood in 1930s film bowls, Bradman in 1990s broadcast drives
  catalog_reel.mp4
      all four back to back, each after one short card (no per-clip cards) - kept <= 50 s

Clips: batter F1 (final_cap, seed 42, 5.6 s real speed), bowler L3 (seed 2024, 2x slow motion = 4.0 s).
Usage:  python scripts/make_catalog.py
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import cv2

from era_filters import apply_preset
from make_final import LABEL, check
from make_sequence import build_sequence, card_frames
from pose_utils import write_video

OUT = Path("data/final/catalog")
WORK = Path("data/final/work")
BOWLER = "data/gen/bowler_raw/L3_s2024_33f.mp4"
BATTER = "data/gen/v3_raw/final_cap_s42_33f.mp4"
ERAS = [("1930s_film", "1932 newsreel"), ("1970s_tv", "1975 television"), ("1990s_broadcast", "1995 broadcast")]


def run_match(out: Path, *extra: str) -> None:
    cmd = [sys.executable, "scripts/make_match.py", "--bowler", BOWLER, "--batter", BATTER, "--bowler-duration", "4.0",
           "--out", str(out), "--style-cards", *extra]
    print(">", " ".join(cmd[1:]))
    subprocess.run(cmd, check=True)


def duration(path: Path) -> float:
    cap = cv2.VideoCapture(str(path))
    d = cap.get(cv2.CAP_PROP_FRAME_COUNT) / (cap.get(cv2.CAP_PROP_FPS) or 1)
    cap.release()
    return d


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    # 1) one match per era (cards filmed in the era)
    for preset, title in ERAS:
        run_match(OUT / f"match_{preset}.mp4", "--preset", preset, "--title", f"{title}: Larwood vs Bradman",
                  "--bowler-card", "Larwood bowls (slow motion)", "--batter-card", "Bradman drives")
    # 2) true cross-era match
    run_match(OUT / "match_crossera.mp4", "--bowler-era", "1930s_film", "--batter-era", "1990s_broadcast",
              "--intro-era", "none", "--title", "Cross-era: Larwood (1930s) vs Bradman (1990s)",
              "--bowler-card", "Larwood, 1930s film", "--batter-card", "Bradman, 1990s broadcast")

    # 3) reel: opening card, then per version one short era card + bowler + batter (styled clips from WORK)
    bstem, tstem = Path(BOWLER).stem, Path(BATTER).stem
    size, fps, sec = (480, 832), 24.0, 1.2
    parts = [write_video(WORK / "reel_open.mp4", card_frames("Cross-Era Fantasy Cricket: the catalog", size, 2.0, fps,
                                                             subtitle=LABEL), fps)]
    versions = [(p, p, t) for p, t in ERAS] + [("1930s_film", "1990s_broadcast", "Cross-era: 1930s bowler, 1990s batter")]
    for bowl_era, bat_era, title in versions:
        frames, cfps = apply_preset(bowl_era, card_frames(title, size, sec, fps, label=False), fps)
        parts.append(write_video(WORK / f"reel_card_{bowl_era}_{bat_era}.mp4", frames, cfps))
        parts.append(WORK / f"{bstem}_retimed_{bowl_era}.mp4")
        parts.append(WORK / f"{tstem}_retimed_{bat_era}.mp4")
    reel = build_sequence([str(p) for p in parts], [None] * len(parts), None, None, OUT / "catalog_reel.mp4", size, fps, sec)

    # 4) checks + docs/CATALOG.md
    rows = []
    files = [OUT / f"match_{p}.mp4" for p, _ in ERAS] + [OUT / "match_crossera.mp4", reel]
    for f in files:
        print(" ", check(Path(f)))
    lines = ["# Cross-era catalog (Milestone 4)", "",
             "All clips are AI-generated (label on every frame) for an academic project. Generated by "
             "`python scripts/make_catalog.py`; files in `data/final/catalog/` (not in git, shared via Drive).", "",
             "| File | Era (bowler / batter) | Players | Source clips | Reference photos | Seeds | Duration |",
             "|---|---|---|---|---|---|---|"]
    era_names = {p: t for p, t in ERAS}
    for p, title in ERAS:
        f = OUT / f"match_{p}.mp4"
        lines.append(f"| `{f.name}` | {title} / {title} | Larwood (bowler, 2x slow motion) vs Bradman (batter) | "
                     "`B1_bowler.mp4` (0-2.0 s), `C2_coverdrive.mp4` (0-5.6 s) | `larwood_crop.png`, `bradman_crop.png` | "
                     f"L3 2024 / F1 42 | {duration(f):.1f} s |")
    f = OUT / "match_crossera.mp4"
    lines.append(f"| `{f.name}` | {era_names['1930s_film']} / {era_names['1990s_broadcast']} | Larwood vs Bradman | "
                 "`B1_bowler.mp4`, `C2_coverdrive.mp4` | `larwood_crop.png`, `bradman_crop.png` | L3 2024 / F1 42 | "
                 f"{duration(f):.1f} s |")
    lines.append(f"| `{Path(reel).name}` | all four versions back to back | Larwood vs Bradman | (as above) | (as above) | "
                 f"L3 2024 / F1 42 | {duration(Path(reel)):.1f} s |")
    lines += ["", "Per-player clips (single era, from `make_final.py`, in `data/final/`):", "",
              "| File | Player | Era | Source clip | Reference | Seed | Duration |", "|---|---|---|---|---|---|---|"]
    for name, player, src, ref, seed in (("final_cap.mp4", "Bradman (F1)", "C2_coverdrive.mp4", "bradman_crop.png", 42),
                                         ("final_bowler.mp4", "Larwood (L3, 2x slow)", "B1_bowler.mp4", "larwood_crop.png", 2024)):
        f = Path("data/final") / name
        if f.exists():
            lines.append(f"| `{name}` | {player} | 1930s film (+ intro card) | `{src}` | `{ref}` | {seed} | {duration(f):.1f} s |")
    for name, player in (("final_eras_cap.mp4", "Bradman (F1)"), ("final_eras_bowler.mp4", "Larwood (L3)")):
        f = Path("data/final") / name
        if f.exists():
            lines.append(f"| `{name}` | {player} | 1930s / 1970s / 1990s back to back | | | | {duration(f):.1f} s |")
    lines += ["", "Photo credits: Larwood - National Library of Australia, Fairfax glass plate, 1929, nla.obj-161865715 "
              "(public domain). Bradman - [TODO: source]. The modern clips are used only to extract motion."]
    Path("docs/CATALOG.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Wrote docs/CATALOG.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
